import test from 'node:test';
import assert from 'node:assert/strict';
import * as L from './lib.js';

test('ترتيب المادة بالحروف والأرقام، ومع أخطاء القراءة الآلية', () => {
  const cases = [['الأولى:', 1], ['الثانية عشر:', 12], ['السادسة عشرة', 16], ['الحادية والعشرون:', 21], ['الثلاتثون', 30],
    ['التاسعة والتلاتون:', 39], ['(16)', 16], ['الأربعون', 40], ['الخامسة بعد المائة', 105], ['١٦', 16],
    ['الحادية عدشير:', 11], ['الرابعة عشير:', 14], ['الثلاتة والثلاثون:', 33], ['السابعة عشر بعد المائة: ملغي.', 117]];
  for (const [s, n] of cases) assert.equal(L.ordinal(s), n, s);
  assert.equal(L.ordinal('كذا'), null);
});

test('تقطيع النظام إلى مواد، وتجاهل الإحالة داخل السطر', () => {
  const pages = [
    'نظام تجريبي\nالمادة الأولى:\nنص الأولى.\nالمادة الثانية: تلتزم الجهة بما يلي:\n1- كذا.',
    'المادة الأربعون ولائحتها التنفيذية.\nتكملة الثانية\nالمادة الثالثة\nنص الثالثة\nwww.moh.gov.sa | Page 2 of 9\nالمادة الرابعة:\nنص الرابعة',
    'اللائحة التنفيذية\nالمادة الأولى:\nأول اللائحة',
  ];
  const a = L.articles(pages);
  assert.deepEqual(a.list.map(x => [x.part, x.n, x.page]), [[1, 1, 1], [1, 2, 1], [1, 3, 2], [1, 4, 2], [2, 1, 3]]);
  assert.match(a.list[1].text, /^تلتزم الجهة بما يلي:\n1- كذا\.\nالمادة الأربعون ولائحتها التنفيذية\.\nتكملة الثانية$/);
  assert.doesNotMatch(a.list[2].text, /moh/);
  assert.equal(a.parts[2], 'اللائحة التنفيذية');
});

const MEMO = `صاحب الفضيلة رئيس الدائرة
إشارة إلى المذكرة المقدمة في القضية رقم (4870000101)، نجيب:
أولاً: الرد على الدفع بعدم الموافقة:
فقد استثنت الفقرة (2) من المادة (7) من اللائحة التنفيذية لنظام المؤسسات الصحية الخاصة "الحالات الطارئة والتي تحتاج لتدخل فوري". وقدمنا البيان وفق المادة (7) من النظام.
ثانياً: الرد على الإهمال:
ما أوجبه نظام مزاولة المهن الصحية؛ إذ نصت المادة (9/أ) على أنه: "يجب أن يستهدف العمل الطبي مصلحة المريض"، ونصت المادة (26) على أن: "التزام الممارس هو التزام ببذل عناية يقظة".
ونصت المادة السادسة عشرة من نظام المؤسسات الصحية الخاصة على العلاج الإسعافي.
الطلبات:
نطلب الحكم.`;

test('أقسام المذكرة بعناوينها', () => {
  const s = L.memoSections(MEMO);
  assert.deepEqual(s.map(x => x.h), ['', 'أولاً: الرد على الدفع بعدم الموافقة', 'ثانياً: الرد على الإهمال', 'الطلبات']);
});

test('الاستشهادات: الفقرة والمادة والنظام والنص المنقول', () => {
  const c = L.citations(MEMO).map(x => [x.n, x.sub, x.reg, x.quote.split(' ').slice(0, 2).join(' ')]);
  assert.deepEqual(c, [
    [7, '2', 'اللائحة التنفيذية لنظام المؤسسات الصحية الخاصة', 'الحالات الطارئة'],
    [7, '', 'نظام المؤسسات الصحية الخاصة', ''],
    [9, 'ا', 'نظام مزاولة المهن الصحية', 'يجب أن'],
    [26, '', 'نظام مزاولة المهن الصحية', 'التزام الممارس'],
    [16, '', 'نظام المؤسسات الصحية الخاصة', ''],
  ]);
});

test('مذكرتنا أم مذكرة الخصم، ونوعها وخصمها ورقم قضيتها', () => {
  assert.equal(L.memoTheirs('مذكرة رد علي النجراني 1'), false);
  assert.equal(L.memoTheirs('مذكرة رد من فلان 1'), true);
  assert.equal(L.memoTheirs('مذكرة رد استئناف مقدمة من فلان.pdf'), true);
  assert.equal(L.memoTheirs('مذكرة جوابية على اعتراض فلان'), false);
  assert.equal(L.memoKind('مذكرة_رد_فلان.docx'), 'مذكرة رد');
  assert.equal(L.memoKind('مذكرة جوابية فلان'), 'مذكرة جوابية');
  assert.equal(L.oppOf('مذكرة جوابية على اعتراض كفاية الله'), 'كفاية الله');
  assert.equal(L.caseNoOf('مذكرة جوابية 4870645324 - فلان.docx', ''), '4870645324');
});

test('الاستعلام: رقم المادة يُفصل، والباقي كلمات', () => {
  assert.deepEqual(L.parseQuery('المادة ١٦ من نظام المؤسسات الصحية'), { art: 16, sub: null, words: ['الموسسات', 'الصحيه'] });
  assert.deepEqual(L.parseQuery('المادة السادسة عشرة المؤسسات'), { art: 16, sub: null, words: ['الموسسات'] });
  assert.deepEqual(L.parseQuery('م16'), { art: 16, sub: null, words: [] });
  assert.deepEqual(L.parseQuery('7/2 المؤسسات'), { art: 7, sub: 2, words: ['الموسسات'] });
});

test('البحث: الكلمة بسوابقها ولواحقها، لا داخل كلمةٍ أخرى', () => {
  const n = L.norm;
  assert.ok(L.matchWord(n('يجب أخذ موافقة المريض'), n('الموافقة')));
  assert.ok(L.matchWord(n('قبل موافقته على العلاج'), n('الموافقة')));
  assert.ok(!L.matchWord(n('في سجل خاص بذلك'), n('بذل')));
  assert.ok(!L.matchWord(n('في الخطة العلاجية'), n('الخطية')));
});

test('البحث: رقم المادة واسم النظام يحدّدان المادة، والعبارة ترفع ما فيه نصّها', () => {
  const docs = [
    { kind: 'ماده', n: 16, docTitle: 'نظام المؤسسات الصحية الخاصة', text: 'تقديم العلاج الإسعافي لجميع الحالات الطارئة' },
    { kind: 'ماده', n: 16, docTitle: 'نظام الرعاية الصحية النفسية', text: 'تلتزم المنشأة بما يأتي' },
    { kind: 'ماده', n: 3, docTitle: 'نظام المؤسسات الصحية الخاصة', text: 'الحالة والطارئة من الأمور المذكورة بعيدًا ' + 'كلام '.repeat(40) + 'الطارئة' },
  ];
  const r = L.search(docs, 'المادة ١٦ المؤسسات');
  assert.equal(r.hits.length, 1);
  assert.equal(r.hits[0].d, docs[0]);
  const r2 = L.search(docs, 'الحالات الطارئة');
  assert.equal(r2.hits[0].d, docs[0]);
});

test('المقتطف يُبرز الكلمة بصورتها في النص', () => {
  const parts = L.snippet('يجب أخذ موافقة المريض الخطية قبل العلاج', [L.norm('الموافقة'), L.norm('الخطية')], 100);
  assert.deepEqual(parts.filter(p => p.hit).map(p => p.t), ['موافقة', 'الخطية']);
});
