test('مذكرتنا: فيها «موكلتي» أو «موكلي»، وإلا فكتبها الخصم بنفسه', () => {
  assert.equal(L.memoOurs('مذكرة جوابية فلان', 'يلتمس المدعى عليه رد الدعوى'), false);
  assert.equal(L.memoOurs('مذكرة رد فلان', 'نطلب إلزامه بأن يدفع لموكلتي'), true);
  assert.equal(L.memoOurs('مذكرة رد من فلان', 'موكلي'), false);
});

test('مذكرتنا أم مذكرة الخصم: العلامات معًا، لا «موكلتي» وحدها', () => {
  const D = 'application/vnd.google-apps.document', PDF = 'application/pdf', team = ['الأحيدب', 'القاسم'];
  // محامي الخصم يقول «موكلي»، ويصف المستشفى بالمدعي
  assert.equal(L.memoOurs('مذكرة جوابية فلان', 'وحيث إن موكلي لم يوقع، وقد قصّر المستشفى المدعي في الإبلاغ', PDF, team), false);
  assert.equal(L.memoOurs('مذكرة جوابية فلان', 'وحيث إن موكلي لم يوقع، وقد قصّر المستشفى المدعي في الإبلاغ', D, team), false);
  // مذكرتنا: الحمادي موكلتنا، ولو كانت PDF
  assert.equal(L.memoOurs('مذكرة رد فلان.pdf', 'المقامة من موكلتي شركة الحمادي القابضة', PDF, team), true);
  assert.equal(L.memoOurs('مذكرة رد فلان', 'نطلب إلزامه بأن يدفع لموكلتي المبلغ', D, team), true);
  // ندافع عن طبيب: «موكلي»، وباسم محامينا في الرأس
  assert.equal(L.memoOurs('مذكرة جوابية د فلان', 'ويمثله عبدالعزيز ابراهيم القاسم … أن موكلي اتبع البروتوكول', D, team), true);
  // رأس مذكرتنا يصف الحمادي «المدعى عليها» وهذا ليس خصومة
  assert.equal(L.memoOurs('مذكرة رد فلان', 'مذكرة رد مقدمة من المدعى عليها/ شركة الحمادي القابضة … منشأة موكلتي', D, team), true);
  assert.equal(L.memoOurs('مذكرة رد من فلان', 'لموكلتي شركة الحمادي', D, team), false);
});

